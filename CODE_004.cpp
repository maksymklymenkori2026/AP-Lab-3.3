#include <iostream>
#include <cmath>
using namespace std;

int main()
{
    double x;
    double y;
    double R;

    cout << "R = "; cin >> R;
    cout << "x = "; cin >> x;

    // в моєму випадку, R впливає на графік наступним чином:
    // -R по X це точка закінчення першої окремої функції, яка є лінійною з нахилом 45 градусів
    // -R до 0 по X це функція чверті кола, радіус цього кола
    // 0 до 6 по X це лінійна функція
    // 6 до безкінечності по X це лінійна функція з кутом 45 градусів

    // перше спостереження, лінійна функція з нахилом 45 градусів це f(x) = x або f(x) = -x

    if (x < -R)
    {
        y = x + R;
    }
    else{
        if (x >= -R && x < 0)
        {
            // тут y визначається між 0 і R, тому що це чверть кола, радіус якого R
            y = sqrt(R*R - x*x);
        }
        else
        {
            if (x >= 0 && x < 6)
            {
                y = R - x*R/6;
            }
            else
            {
                y = x - 6;
            }
        }
    }

    cout << "y = " << y << endl;
    cin.get();
    return 0;
}